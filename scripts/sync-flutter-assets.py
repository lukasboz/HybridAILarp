#!/usr/bin/env python3
"""Bundle existing shared product data and public Firebase client configuration."""
import json
import pathlib
import plistlib
import shutil

ROOT = pathlib.Path(__file__).resolve().parents[1]
assets = ROOT / 'app/assets'
for source, target in [('shared', 'shared'), ('web/assets/activities', 'activities'),
                       ('web/assets/fonts', 'fonts')]:
    shutil.copytree(ROOT / source, assets / target, dirs_exist_ok=True)

tokens = json.loads((ROOT / 'shared/design-tokens.json').read_text())
dart = "// Generated by scripts/sync-flutter-assets.py.\nimport 'dart:ui';\n\nabstract final class DesignTokens {\n"
for name, value in tokens['colors'].items():
    dart += f"  static const {name} = Color(0xFF{value[1:]});\n"
for name, value in tokens['sizes'].items():
    dart += f"  static const double {name} = {value};\n"
dart += '}\n'
(ROOT / 'app/lib/design_tokens.dart').write_text(dart)

config = {'web': {}, 'android': {}, 'ios': {}, 'appCheckSiteKey': '',
          'cloudModel': 'gemini-3.8-flash',
          'publicWebUrl': 'https://meethalfway-2026-e43ca6.web.app/', 'emulator': False}
web = ROOT / 'web/firebase-config.local.json'
if web.exists():
    existing = json.loads(web.read_text())
    config.update({key: existing[key] for key in ['appCheckSiteKey', 'cloudModel', 'publicWebUrl', 'emulator'] if key in existing})
    config['web'] = existing.get('firebase', {})
android = ROOT / 'native/android/app/google-services.json'
if android.exists():
    data = json.loads(android.read_text())
    client = next(c for c in data['client'] if c['client_info']['android_client_info']['package_name'] == 'app.meethalfway.mobile')
    config['android'] = {'apiKey': client['api_key'][0]['current_key'],
                         'appId': client['client_info']['mobilesdk_app_id'],
                         'projectId': data['project_info']['project_id'],
                         'messagingSenderId': data['project_info']['project_number'],
                         'storageBucket': data['project_info'].get('storage_bucket', '')}
ios = ROOT / 'native/ios/Resources/GoogleService-Info.plist'
if ios.exists():
    data = plistlib.loads(ios.read_bytes())
    config['ios'] = {key: data[source] for key, source in {
        'apiKey': 'API_KEY', 'appId': 'GOOGLE_APP_ID', 'projectId': 'PROJECT_ID',
        'messagingSenderId': 'GCM_SENDER_ID', 'iosBundleId': 'BUNDLE_ID',
        'storageBucket': 'STORAGE_BUCKET'}.items() if source in data}
(assets / 'firebase.json').write_text(json.dumps(config, indent=2) + '\n')
print('Bundled Flutter catalogue, design tokens, Inter fonts, photographs and public client configuration.')
